#!/bin/bash
# run_pipeline.sh -- runs Stage 4 through Stage 9 in one go, to build a
# bigger, more solid dataset and a freshly trained model ahead of your
# presentation, without typing 10 separate commands by hand.
#
# WHAT IT DOES, IN ORDER
# -------------------------
#   1. Generates normal traffic, TWICE, at a longer duration than the
#      original single-command default -- more realistic normal data.
#   2. Simulates the attack, TWICE, at a longer duration -- more attack
#      examples for the model to learn from.
#   3. Builds the combined dataset from every capture (all 4 pcap sets).
#   4. Trains the model on that bigger dataset.
#
# It does NOT run run_detection_demo.py -- run that separately, live, as
# your actual demo in front of your teacher, after this has finished.
#
# HOW TO RUN IT
# ----------------
#   cd arp-spoofing-detector
#   chmod +x run_pipeline.sh
#   ./run_pipeline.sh
#
# It calls 'sudo' itself only for the stages that need it (Mininet), so
# you don't need to prefix the whole command with sudo.
#
# You can change how much data gets generated by editing the durations
# below.

set -e   # stop immediately if any stage fails, instead of plowing on

NORMAL_DURATION=120     # seconds per normal-traffic run (default was 60)
ATTACK_DURATION=60      # seconds per attack run (default was 30)

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

section() {
    echo ""
    echo "=================================================================="
    echo "  $1"
    echo "=================================================================="
}

section "Stage 4, run 1/2: normal traffic (${NORMAL_DURATION}s)"
sudo mn -c > /dev/null 2>&1 || true
(cd "$SCRIPT_DIR/capture" && \
    sudo env DURATION_SECONDS=$NORMAL_DURATION CAPTURE_RUN_ID=run1 \
    python3 generate_normal_traffic.py)

section "Stage 4, run 2/2: normal traffic (${NORMAL_DURATION}s)"
sudo mn -c > /dev/null 2>&1 || true
(cd "$SCRIPT_DIR/capture" && \
    sudo env DURATION_SECONDS=$NORMAL_DURATION CAPTURE_RUN_ID=run2 \
    python3 generate_normal_traffic.py)

section "Stage 5, run 1/2: attack simulation (${ATTACK_DURATION}s)"
sudo mn -c > /dev/null 2>&1 || true
(cd "$SCRIPT_DIR/attack" && \
    sudo env DURATION_SECONDS=$ATTACK_DURATION CAPTURE_RUN_ID=run1 \
    python3 simulate_attack.py)

section "Stage 5, run 2/2: attack simulation (${ATTACK_DURATION}s)"
sudo mn -c > /dev/null 2>&1 || true
(cd "$SCRIPT_DIR/attack" && \
    sudo env DURATION_SECONDS=$ATTACK_DURATION CAPTURE_RUN_ID=run2 \
    python3 simulate_attack.py)

section "Stage 6: building the combined dataset"
(cd "$SCRIPT_DIR/dataset" && python3 build_dataset.py)

section "Stages 7-9: training the model"
(cd "$SCRIPT_DIR/model" && python3 train_model.py)

section "Done"
echo "Dataset: dataset/arp_dataset.csv"
echo "Model:   model/arp_model.pkl"
echo ""
echo "Next: run the live demo yourself, on stage, with:"
echo "    cd detector && sudo python3 run_detection_demo.py"